begin;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '' check (char_length(full_name) <= 100),
  onboarding_step text not null default 'choose' check (onboarding_step in ('choose','provider_form','complete')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.categories (
  id integer generated by default as identity primary key,
  name text not null unique,
  is_active boolean not null default true
);
insert into public.categories(name) values
 ('Eletricista'),('Diarista'),('Professor(a) particular'),('Encanador(a)'),
 ('Cabeleireiro(a)'),('Pintor(a)'),('Jardineiro(a)'),('Montador(a) de móveis'),('Reparador(a) de celular');

create table public.providers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  display_name text not null default '' check (char_length(display_name) <= 80),
  category_id integer references public.categories(id) on delete restrict,
  description text not null default '' check (char_length(description) <= 1000),
  city text not null default '' check (char_length(city) <= 100),
  state text not null default '' check (state = '' or state in ('AC','AL','AP','AM','BA','CE','DF','ES','GO','MA','MT','MS','MG','PA','PB','PR','PE','PI','RJ','RN','RS','RO','RR','SC','SP','SE','TO')),
  whatsapp text not null default '' check (char_length(whatsapp) <= 20),
  service_modes text[] not null default '{}' check (service_modes <@ array['at_customer','own_location','online']::text[] and array_position(service_modes, null) is null),
  service_regions text not null default '' check (char_length(service_regions) <= 200),
  status text not null default 'draft' check (status in ('draft','published')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint published_fields check (status = 'draft' or (
    char_length(btrim(display_name)) > 0 and category_id is not null
    and char_length(btrim(description)) >= 10 and char_length(btrim(city)) > 0
    and state <> '' and whatsapp ~ '^55[0-9]{10,11}$' and cardinality(service_modes) > 0
  ))
);
create index providers_search_idx on public.providers(status, category_id, state, id);
create table public.favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  provider_id uuid not null references public.providers(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(user_id, provider_id)
);
create index favorites_provider_idx on public.favorites(provider_id);

create function public.touch_updated_at() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
create trigger profiles_updated before update on public.profiles for each row execute function public.touch_updated_at();
create trigger providers_updated before update on public.providers for each row execute function public.touch_updated_at();

create function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(id, full_name)
  values (new.id, left(coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', ''),100));
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
-- Permite aplicar a migração em projeto onde já existam contas, sem copiar dados locais.
insert into public.profiles(id,full_name)
select id,left(coalesce(raw_user_meta_data->>'full_name',raw_user_meta_data->>'name',''),100) from auth.users
on conflict(id) do nothing;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.providers enable row level security;
alter table public.favorites enable row level security;
revoke all on public.profiles, public.categories, public.providers, public.favorites from anon, authenticated;
grant select, update(full_name,onboarding_step) on public.profiles to authenticated;
grant select on public.categories to authenticated;
grant select, insert, delete, update(display_name,category_id,description,city,state,whatsapp,service_modes,service_regions,status) on public.providers to authenticated;
grant select, insert, delete on public.favorites to authenticated;

create policy profiles_read on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy profiles_update on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
create policy categories_read on public.categories for select to authenticated using (true);
create policy providers_read on public.providers for select to authenticated using (status = 'published' or user_id = (select auth.uid()));
create policy providers_insert on public.providers for insert to authenticated with check (user_id = (select auth.uid()));
create policy providers_update on public.providers for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy providers_delete on public.providers for delete to authenticated using (user_id = (select auth.uid()));
create policy favorites_read on public.favorites for select to authenticated using (user_id = (select auth.uid()));
create policy favorites_insert on public.favorites for insert to authenticated with check (
  user_id = (select auth.uid()) and exists(select 1 from public.providers p where p.id = provider_id and p.status = 'published')
);
create policy favorites_delete on public.favorites for delete to authenticated using (user_id = (select auth.uid()));

-- As funções do aplicativo usam os privilégios do chamador: RLS permanece aplicada.
create function public.begin_provider() returns public.providers language plpgsql security invoker set search_path = '' as $$
declare result public.providers;
begin
  if auth.uid() is null then raise exception 'Sessão necessária' using errcode='42501'; end if;
  insert into public.providers(user_id,display_name)
    select id,left(full_name,80) from public.profiles where id=auth.uid()
    on conflict(user_id) do nothing;
  select * into strict result from public.providers where user_id=auth.uid();
  if result.status='draft' then
    update public.profiles set onboarding_step='provider_form' where id=auth.uid() and onboarding_step<>'complete';
  end if;
  return result;
end;
$$;

create function public.save_provider(p_data jsonb, p_publish boolean) returns public.providers
language plpgsql security invoker set search_path = '' as $$
declare result public.providers;
begin
  if auth.uid() is null then raise exception 'Sessão necessária' using errcode='42501'; end if;
  if p_publish is null or p_data is null then raise exception 'Dados obrigatórios' using errcode='23514'; end if;
  -- Não transformar um perfil já publicado em rascunho por um cliente desatualizado.
  if not p_publish and exists(select 1 from public.providers where user_id=auth.uid() and status='published') then
    raise exception 'Perfil já publicado; atualize a tela' using errcode='23514';
  end if;
  if p_publish and not exists(select 1 from public.categories where id=(p_data->>'category_id')::integer and is_active) then
    raise exception 'Categoria indisponível' using errcode='23514';
  end if;
  insert into public.providers(user_id,display_name,category_id,description,city,state,whatsapp,service_modes,service_regions,status)
  values(auth.uid(),btrim(coalesce(p_data->>'display_name','')),(p_data->>'category_id')::integer,
    btrim(coalesce(p_data->>'description','')),btrim(coalesce(p_data->>'city','')),upper(btrim(coalesce(p_data->>'state',''))),
    coalesce(p_data->>'whatsapp',''),array(select jsonb_array_elements_text(coalesce(p_data->'service_modes','[]'::jsonb))),
    btrim(coalesce(p_data->>'service_regions','')),case when p_publish then 'published' else 'draft' end)
  on conflict(user_id) do update set display_name=excluded.display_name,category_id=excluded.category_id,
    description=excluded.description,city=excluded.city,state=excluded.state,whatsapp=excluded.whatsapp,
    service_modes=excluded.service_modes,service_regions=excluded.service_regions,status=excluded.status
  returning * into result;
  update public.profiles set onboarding_step='complete' where id=auth.uid();
  return result;
end;
$$;

create function public.normalize_search(value text) returns text language sql immutable strict set search_path = '' as $$
  select translate(lower(value),'áàâãäéèêëíìîïóòôõöúùûüç','aaaaaeeeeiiiiooooouuuuc');
$$;
create function public.search_providers(p_name text default '', p_city text default '', p_state text default '',
  p_category integer default null, p_offset integer default 0, p_limit integer default 20)
returns setof public.providers language sql stable security invoker set search_path = '' as $$
  select * from public.providers p where p.status='published'
    and position(public.normalize_search(coalesce(p_name,'')) in public.normalize_search(p.display_name))>0
    and position(public.normalize_search(coalesce(p_city,'')) in public.normalize_search(p.city))>0
    and (coalesce(p_state,'')='' or p.state=upper(p_state))
    and (p_category is null or p.category_id=p_category)
  order by p.id limit least(greatest(p_limit,1),50) offset greatest(p_offset,0);
$$;

revoke execute on function public.handle_new_user(),public.touch_updated_at() from public,anon,authenticated;
revoke execute on function public.begin_provider(),public.save_provider(jsonb,boolean),public.search_providers(text,text,text,integer,integer,integer),public.normalize_search(text) from public,anon;
grant execute on function public.begin_provider(),public.save_provider(jsonb,boolean),public.search_providers(text,text,text,integer,integer,integer),public.normalize_search(text) to authenticated;
commit;
